import {
  BaseError,
  ContractFunctionRevertedError,
  stringToHex,
  type Address,
  type Abi,
  type Hex,
} from "viem";
import { KernelAbi } from "../../abis/Kernel";
import type { ControlBlock } from "./control-state";
import type { EnvioContext, ContractEntity } from "./types";
import {
  completeRelationshipBlock,
  type RelationshipField,
  type RelationshipState,
} from "./ownership";

type Client = {
  getBlock: (input: { blockNumber: bigint }) => Promise<{ hash: Hex | null }>;
  readContract: (input: {
    address: Address;
    abi: Abi;
    functionName: string;
    args: readonly unknown[];
    blockHash: Hex;
    requireCanonical: true;
  }) => Promise<unknown>;
};
export type DependencyReadResult =
  | { status: "success"; module: string; policies: string[] }
  | { status: "unavailable"; reason: string };

/** Read the Kernel registry: read-only module users do not appear in requestPermissions(). */
export async function readPinnedModuleDependencies(
  client: Client,
  input: {
    kernel: string;
    keycode: string;
    blockNumber: bigint;
    blockHash: string;
  }
): Promise<DependencyReadResult> {
  try {
    if (!/^[A-Z]{5}$/.test(input.keycode)) throw new Error("Invalid keycode");
    const canonical = async () =>
      (await client.getBlock({ blockNumber: input.blockNumber })).hash ===
      input.blockHash;
    if (!(await canonical())) throw new Error("Canonical block changed");
    const read = (
      functionName: "getModuleForKeycode" | "moduleDependents",
      args: readonly unknown[]
    ) =>
      client.readContract({
        address: input.kernel as Address,
        abi: KernelAbi,
        functionName,
        args,
        blockHash: input.blockHash as Hex,
        requireCanonical: true,
      });
    const keycode = stringToHex(input.keycode, { size: 5 });
    const module = await read("getModuleForKeycode", [keycode]);
    if (typeof module !== "string" || !/^0x[0-9a-f]{40}$/i.test(module))
      throw new Error("Invalid module address");
    const policies: string[] = [];
    for (let index = 0; index < 1024; index++) {
      try {
        const policy = await read("moduleDependents", [keycode, BigInt(index)]);
        if (
          typeof policy !== "string" ||
          !/^0x[0-9a-f]{40}$/i.test(policy) ||
          /^0x0{40}$/i.test(policy) ||
          policies.includes(policy.toLowerCase())
        )
          throw new Error("Invalid dependent");
        policies.push(policy.toLowerCase());
      } catch (error) {
        const revert =
          error instanceof BaseError
            ? error.walk(
                (cause) => cause instanceof ContractFunctionRevertedError
              )
            : undefined;
        // This known Kernel method is an autogenerated array getter. Older
        // compilers use an empty EVM revert for bounds, newer ones use Panic(0x32).
        // A transport failure or a nonempty contract error never terminates the scan.
        const bounds =
          revert instanceof ContractFunctionRevertedError &&
          ((revert.data?.errorName === "Panic" &&
            revert.data.args?.[0] === 50n) ||
            (!revert.data &&
              (!revert.raw || revert.raw === "0x") &&
              (!revert.reason || revert.reason === "execution reverted") &&
              !revert.signature));
        if (!bounds) throw error;
        if (!(await canonical())) throw new Error("Canonical block changed");
        if (/^0x0{40}$/i.test(module) && policies.length)
          throw new Error("Dependents have no installed module");
        return { status: "success", module: module.toLowerCase(), policies };
      }
    }
    throw new Error("Dependency scan limit reached");
  } catch {
    return {
      status: "unavailable",
      reason: "Canonical Kernel dependency registry unavailable or incomplete",
    };
  }
}

export async function getModuleDependencyFields(
  context: EnvioContext,
  chainId: number
): Promise<RelationshipField[]> {
  const rows = await context.ContractRelationship.getWhere<RelationshipState>({
    chainId: { _eq: chainId },
    kind: { _eq: "module-dependency" },
  });
  return rows.map((row) => ({
    address: row.subject,
    getter: row.getter,
    kind: row.kind,
    startBlock: Number(row.seed?.number ?? row.provenance.number),
    coverage: row.coverage,
  }));
}

export async function completeModuleDependencies(
  context: EnvioContext,
  chainId: number,
  block: ControlBlock,
  previous: RelationshipField[],
  read: (keycode: string) => Promise<DependencyReadResult>,
  readBlock: (number: string) => Promise<ControlBlock | undefined>
) {
  const modules = await context.Contract.getWhere<ContractEntity>({
    chainId: { _eq: chainId },
    contractType: { _eq: "MODULE" },
  });
  const keycodes = new Set(
    [
      ...modules.map((module) => module.name),
      ...previous.map((field) => field.getter.split(":")[1]),
    ].filter((keycode): keycode is string =>
      Boolean(keycode && /^[A-Z]{5}$/.test(keycode))
    )
  );
  for (const keycode of keycodes) {
    const result = await read(keycode);
    const getter = `moduleDependents:${keycode}`;
    const addresses = new Set([
      ...previous
        .filter((field) => field.getter === getter)
        .map((field) => field.address),
      ...(result.status === "success" ? result.policies : []),
    ]);
    const fields = [...addresses].map((address) => ({
      address,
      getter,
      kind: "module-dependency",
      startBlock: Number(block.number),
      coverage:
        "getter-only: Kernel.moduleDependents records configured module dependencies, including read-only use; observed at completed canonical checkpoints, without inferring earlier transitions.",
    }));
    if (
      !(await completeRelationshipBlock(
        context,
        chainId,
        block,
        fields,
        async (address) =>
          result.status === "unavailable"
            ? result
            : {
                status: "success",
                value: result.policies.includes(address)
                  ? result.module
                  : `0x${"0".repeat(40)}`,
                functionContext: {
                  signature: "Kernel.moduleDependents(bytes5,uint256)",
                },
              },
        readBlock
      ))
    )
      return false;
  }
  return true;
}
